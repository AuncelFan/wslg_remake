$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$temporary = Join-Path ([IO.Path]::GetTempPath()) ('wslg-workarea-tests-' + [Guid]::NewGuid().ToString('N'))
$null = New-Item -ItemType Directory -Path $temporary
$binary = Join-Path $temporary 'tests.exe'
try {
    $compiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
    & $compiler /nologo /target:exe /platform:x64 /optimize+ /debug- /main:WorkAreaSyncTests /reference:System.Windows.Forms.dll /reference:System.Web.Extensions.dll "/out:$binary" (Join-Path $root 'tools\windows\workarea_sync.cs') (Join-Path $PSScriptRoot 'workarea_sync_harness.cs')
    if ($LASTEXITCODE -ne 0) { throw 'Could not compile work-area tests.' }
    & $binary
    if ($LASTEXITCODE -ne 0) { throw 'Work-area tests failed.' }
} finally {
    # The temporary directory is freshly generated by this script. Delete exact files only.
    if (Test-Path -LiteralPath $binary) { Remove-Item -LiteralPath $binary }
    if (Test-Path -LiteralPath $temporary) { Remove-Item -LiteralPath $temporary }
}
